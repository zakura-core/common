struct glv_half_t {
    bool negative;
    uint64_t magnitude[2];
};

static bool signed_half(const uint64_t value[4], glv_half_t& output)
{
    uint64_t extension = value[1] >> 63 ? UINT64_MAX : 0;
    if (value[2] != extension || value[3] != extension)
        return false;

    output.negative = value[3] >> 63;
    if (output.negative) {
        output.magnitude[0] = ~value[0] + 1;
        output.magnitude[1] =
            ~value[1] + (output.magnitude[0] == 0);
    } else {
        output.magnitude[0] = value[0];
        output.magnitude[1] = value[1];
    }
    return (output.magnitude[1] >> 63) == 0;
}

struct glv_split_t {
    glv_half_t first;
    glv_half_t second;
};

static const size_t PASTA_SCALAR_BYTES = 32;
static const size_t GLV_BITS = 127;
static const size_t GLV_BYTES = (GLV_BITS + 7) / 8;

static bool glv_decompose(const unsigned char scalar[PASTA_SCALAR_BYTES],
                          const glv_params_t& params, glv_split_t& output)
{
    uint64_t scalar_limbs[4];
    for (size_t i = 0; i < 4; i++)
        scalar_limbs[i] = load64_le(&scalar[8 * i]);

    uint64_t c1[2], c2[2];
    if (!round_mul_shift(params.g1, scalar_limbs, c1) ||
        !round_mul_shift(params.g2, scalar_limbs, c2)) {
        return false;
    }

    uint64_t c1v1a[4], c2v2a[4], c1v1b[4], c2v2b[4];
    mul128(c1, params.v1a, c1v1a);
    mul128(c2, params.v2a, c2v2a);
    mul128(c1, params.v1b_negative, c1v1b);
    mul128(c2, params.v2b, c2v2b);

    uint64_t intermediate[4], first[4], second[4];
    sub256(scalar_limbs, c1v1a, intermediate);
    sub256(intermediate, c2v2a, first);
    sub256(c1v1b, c2v2b, second);
    return signed_half(first, output.first) &&
           signed_half(second, output.second);
}

static void store_half(unsigned char output[GLV_BYTES],
                       const glv_half_t& half)
{
    store64_le(&output[0], half.magnitude[0]);
    store64_le(&output[8], half.magnitude[1]);
}

template<class affine_t, class field_t>
static affine_t pasta_endomorphism(const affine_t& point,
                                   const field_t& zeta)
{
    affine_t output = point;
    output.X *= zeta;
    return output;
}

template<class point_t, class scalar_t, class field_t,
         class affine_t = typename point_t::affine_type>
static void mult_pippenger_glv_signed_serial(
    point_t& output, const affine_t points[], size_t npoints,
    const scalar_t montgomery_scalars[], const glv_params_t& params,
    const field_t& zeta)
{
    using canonical_scalar = typename scalar_t::pow_t;
    static_assert(sizeof(scalar_t) == PASTA_SCALAR_BYTES,
                  "Pasta scalars must contain exactly 32 bytes");

    if (npoints == 0) {
        output.inf();
        return;
    }

    if (npoints > std::numeric_limits<size_t>::max() /
                      (2 * GLV_BYTES)) {
        mult_pippenger_signed_serial(
            output, points, npoints, montgomery_scalars);
        return;
    }

    // Canonicalize all scalars in one pass before expanding the point set.
    std::unique_ptr<canonical_scalar[]> canonical_scalars(
        new canonical_scalar[npoints]);
    for (size_t i = 0; i < npoints; i++)
        montgomery_scalars[i].to_scalar(canonical_scalars[i]);

    const size_t expanded_npoints = 2 * npoints;
    std::vector<affine_t> expanded_points(expanded_npoints);
    std::vector<unsigned char> expanded_scalars(
        expanded_npoints * GLV_BYTES);
    for (size_t i = 0; i < npoints; i++) {
        glv_split_t split;
        bool valid = glv_decompose(canonical_scalars[i], params, split);
        assert(valid && "Pasta GLV decomposition must fit signed halves");
        if (!valid) {
            // Keep release builds correct if the constants or arithmetic are
            // ever changed without preserving the checked GLV bounds.
            mult_pippenger_signed_serial(
                output, points, npoints, montgomery_scalars);
            return;
        }

        expanded_points[2 * i] = points[i];
        expanded_points[2 * i].cneg(split.first.negative);
        store_half(&expanded_scalars[2 * i * GLV_BYTES], split.first);

        expanded_points[2 * i + 1] =
            pasta_endomorphism(points[i], zeta);
        expanded_points[2 * i + 1].cneg(split.second.negative);
        store_half(
            &expanded_scalars[(2 * i + 1) * GLV_BYTES], split.second);
    }

    mult_pippenger_signed_serial_raw(
        output, expanded_points.data(), expanded_npoints,
        expanded_scalars.data(), GLV_BITS);

#ifndef NDEBUG
    point_t expected;
    mult_pippenger_signed_serial(
        expected, points, npoints, montgomery_scalars);
    affine_t actual_affine = output.to_affine();
    affine_t expected_affine = expected.to_affine();
    assert(actual_affine.X == expected_affine.X &&
           actual_affine.Y == expected_affine.Y);
#endif
}

