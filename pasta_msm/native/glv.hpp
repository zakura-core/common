struct mac64_t {
    uint64_t low;
    uint64_t high;
};

static mac64_t mac64(uint64_t accumulator, uint64_t left, uint64_t right,
                     uint64_t carry)
{
#if defined(_MSC_VER) && defined(_M_X64)
    uint64_t low;
    uint64_t high = _umul128(left, right, &low);
#elif defined(__SIZEOF_INT128__)
    unsigned __int128 product =
        static_cast<unsigned __int128>(left) * right;
    uint64_t low = static_cast<uint64_t>(product);
    uint64_t high = static_cast<uint64_t>(product >> 64);
#else
    const uint64_t left_low = static_cast<uint32_t>(left);
    const uint64_t left_high = left >> 32;
    const uint64_t right_low = static_cast<uint32_t>(right);
    const uint64_t right_high = right >> 32;
    const uint64_t product_low = left_low * right_low;
    const uint64_t product_middle =
        (product_low >> 32) +
        static_cast<uint32_t>(left_low * right_high) +
        static_cast<uint32_t>(left_high * right_low);
    uint64_t low = (product_middle << 32) |
                   static_cast<uint32_t>(product_low);
    uint64_t high = left_high * right_high +
                    (left_low * right_high >> 32) +
                    (left_high * right_low >> 32) +
                    (product_middle >> 32);
#endif

    uint64_t sum = low + accumulator;
    high += sum < low;
    low = sum + carry;
    high += low < sum;
    return mac64_t{low, high};
}

static void schoolbook_mul(const uint64_t left[], size_t left_len,
                           const uint64_t right[], size_t right_len,
                           uint64_t product[])
{
    for (size_t i = 0; i < left_len; i++) {
        uint64_t carry = 0;
        for (size_t j = 0; j < right_len; j++) {
            mac64_t limb =
                mac64(product[i + j], left[i], right[j], carry);
            product[i + j] = limb.low;
            carry = limb.high;
        }
        product[i + right_len] = carry;
    }
}

// Computes round((coefficient * scalar) / 2^384), rejecting a result that
// does not fit the two output limbs.
static bool round_mul_shift(const uint64_t coefficient[5],
                            const uint64_t scalar[4], uint64_t output[2])
{
    uint64_t product[9] = {};
    schoolbook_mul(coefficient, 5, scalar, 4, product);

    uint64_t round = product[5] >> 63;
    output[0] = product[6] + round;
    uint64_t carry = output[0] < product[6];
    output[1] = product[7] + carry;
    return product[8] == 0 && output[1] >= product[7];
}

static void mul128(const uint64_t left[2], const uint64_t right[2],
                   uint64_t output[4])
{
    output[0] = output[1] = output[2] = output[3] = 0;
    schoolbook_mul(left, 2, right, 2, output);
}

static void sub256(const uint64_t left[4], const uint64_t right[4],
                   uint64_t output[4])
{
    uint64_t borrow = 0;
    for (size_t i = 0; i < 4; i++) {
        uint64_t difference = left[i] - right[i];
        uint64_t next_borrow = left[i] < right[i];
        output[i] = difference - borrow;
        next_borrow |= difference < borrow;
        borrow = next_borrow;
    }
}

static uint64_t load64_le(const unsigned char bytes[8])
{
    uint64_t output = 0;
    for (size_t i = 0; i < 8; i++)
        output |= static_cast<uint64_t>(bytes[i]) << (8 * i);
    return output;
}

static void store64_le(unsigned char bytes[8], uint64_t value)
{
    for (size_t i = 0; i < 8; i++) {
        bytes[i] = static_cast<unsigned char>(value);
        value >>= 8;
    }
}

