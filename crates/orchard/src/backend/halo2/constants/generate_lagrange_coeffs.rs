use alloc::{string::String, vec::Vec};
use std::{fmt::Write, path::PathBuf};

use crate::backend::ff::PrimeField;
use crate::backend::halo2_gadgets::ecc::chip::{
    FixedPoint, FixedScalarKind, constants::compute_lagrange_coeffs,
};
use crate::backend::pasta_curves::pallas;
use crate::constants::fixed_bases::{
    NUM_WINDOWS, NUM_WINDOWS_SHORT, OrchardBaseFieldBases, OrchardFixedBasesFull,
    OrchardShortScalarBases,
};

/// Emits one table. The window count comes from the base's
/// `FixedScalarKind`, exactly as the `FixedPoint::lagrange_coeffs` default
/// derives it, so the generated table cannot disagree with the trait.
fn emit<B: FixedPoint<pallas::Affine>>(output: &mut String, name: &str, base: B) {
    let windows = <B::FixedScalarKind as FixedScalarKind>::NUM_WINDOWS;
    let length = match windows {
        NUM_WINDOWS => "NUM_WINDOWS",
        NUM_WINDOWS_SHORT => "NUM_WINDOWS_SHORT",
        other => panic!("no named constant for {other} windows"),
    };
    writeln!(
        output,
        "#[rustfmt::skip]\npub(super) static {name}: [[pallas::Base; H]; {length}] = ["
    )
    .unwrap();
    for window in compute_lagrange_coeffs(base.generator(), windows) {
        writeln!(output, "    [").unwrap();
        for coefficient in window {
            let repr = coefficient.to_repr();
            let limbs: Vec<u64> = repr
                .as_ref()
                .as_chunks::<8>()
                .0
                .iter()
                .map(|limb| u64::from_le_bytes(*limb))
                .collect();
            writeln!(
                output,
                "        pallas::Base::from_raw([0x{:016x}, 0x{:016x}, 0x{:016x}, 0x{:016x}]),",
                limbs[0], limbs[1], limbs[2], limbs[3],
            )
            .unwrap();
        }
        writeln!(output, "    ],").unwrap();
    }
    writeln!(output, "];\n").unwrap();
}

#[test]
#[ignore = "set ORCHARD_LAGRANGE_OUTPUT to regenerate private tables"]
fn generate_lagrange_coeffs() {
    let path = PathBuf::from(
        std::env::var_os("ORCHARD_LAGRANGE_OUTPUT").expect("set ORCHARD_LAGRANGE_OUTPUT"),
    );
    let mut output = String::from(
        "// Generated by the private generate_lagrange_coeffs maintenance test.\n\n\
         use crate::backend::pasta_curves::pallas;\n\n\
         use super::{H, NUM_WINDOWS, NUM_WINDOWS_SHORT};\n\n",
    );

    emit(
        &mut output,
        "COMMIT_IVK_R",
        OrchardFixedBasesFull::CommitIvkR,
    );
    emit(
        &mut output,
        "NOTE_COMMIT_R",
        OrchardFixedBasesFull::NoteCommitR,
    );
    emit(
        &mut output,
        "VALUE_COMMIT_R",
        OrchardFixedBasesFull::ValueCommitR,
    );
    emit(
        &mut output,
        "SPEND_AUTH_G",
        OrchardFixedBasesFull::SpendAuthG,
    );
    emit(
        &mut output,
        "NULLIFIER_K",
        OrchardBaseFieldBases::NullifierK,
    );
    emit(
        &mut output,
        "VALUE_COMMIT_V",
        OrchardShortScalarBases::ValueCommitV,
    );
    emit(
        &mut output,
        "SPEND_AUTH_G_SHORT",
        OrchardShortScalarBases::SpendAuthGShort,
    );

    output.pop();
    std::fs::write(path, output).unwrap();
}
