//! One isolated measurement leg, orchestrated by `scripts/sensei-bench`.

use std::{collections::BTreeSet, hint::black_box, num::NonZeroUsize, path::Path, time::Instant};

use orchard::circuit::{OrchardCircuitVersion, Proof, ProofBatch, ProvingKey, VerifyingKey};
use rand::{SeedableRng, rngs::StdRng};
use serde::{Deserialize, Serialize};
use serde_json::json;

mod support;

// The driver selects and checks arithmetic from Cargo's resolved build records.
// Report `portable` below so it also checks the executable's selected mode.

/// Version four identifies the measured operation, the shared verifier corpus,
/// and whole-binary backend selection.
const PROTOCOL_VERSION: u8 = 4;
/// The deterministic corpus format is versioned separately from worker output.
const CORPUS_VERSION: u8 = 1;
/// Corpus proof randomness is independent of measured prover randomness.
const CORPUS_DOMAIN: u64 = 0x73656e7365690004;
/// BLAKE2b-256 binds each verifier leg to the driver's recorded corpus.
const CORPUS_HASH_BYTES: usize = 32;
/// Distinct domains prevent warmup randomness entering measurements.
const WARMUP_DOMAIN: u64 = 0x73656e7365690002;
const SAMPLE_DOMAIN: u64 = 0x73656e7365690003;
/// Compare two adjacent windows, with at least ten complete warmup calls.
const WARMUP_WINDOW: usize = 5;
/// Five percent is also the driver's drift and precision warning threshold.
const STABILITY_TOLERANCE: f64 = 0.05;
/// Bound extra warming when the machine never settles.
const MAX_WARMUP_SECONDS: f64 = 30.0;
/// StdRng's seed holds four independently encoded 64-bit components.
const SEED_COMPONENT_BYTES: usize = size_of::<u64>();
/// Normal legs take a mode, batch size, and five measurement parameters.
const LEG_ARGUMENTS: usize = 7;
/// Corpus generation takes its command, output directory, count, and workers.
const GENERATE_ARGUMENTS: usize = 4;

#[derive(Serialize, Deserialize)]
struct VerifierCorpus {
    version: u8,
    actions: usize,
    proofs: Vec<Vec<u8>>,
}

fn payment_fixture(actions: usize) -> support::PaymentFixture {
    match actions {
        1 => support::payment_fixture(1),
        2 => support::two_real_spends_payment_fixture(),
        _ => panic!("only one Action or two real spends are supported"),
    }
}

fn requested_workers(value: &str) -> Option<NonZeroUsize> {
    (value != "default").then(|| value.parse().expect("positive worker count"))
}

fn initialize_workers(requested: Option<NonZeroUsize>, verifier: bool) -> usize {
    if let Some(workers) = requested {
        // Keep native work on the calling thread to preserve its usual scheduling.
        rayon::ThreadPoolBuilder::new()
            .num_threads(workers.get())
            .build_global()
            .expect("configure global workers before initialization");
        assert_eq!(rayon::current_num_threads(), workers.get());
    }
    #[cfg(feature = "backend-sensei")]
    {
        // Verifier legs must not pay for (or hide) prover preparation.
        if verifier {
            sensei::benchmark_initialize_verifier(requested)
                .expect("initialize Sensei verifier with the requested worker policy")
                .get()
        } else {
            sensei::benchmark_initialize(requested)
                .expect("initialize Sensei with the requested worker policy")
                .get()
        }
    }
    #[cfg(not(feature = "backend-sensei"))]
    {
        let _ = verifier;
        rayon::current_num_threads()
    }
}

#[allow(
    clippy::assertions_on_constants,
    reason = "corpus generation must fail at runtime in non-native benchmark builds"
)]
fn generate_corpus(directory: &Path, count: usize) {
    assert!(
        cfg!(feature = "backend-halo2"),
        "verifier fixtures must be generated by the native backend"
    );
    assert!(count >= 2 * WARMUP_WINDOW);
    let pk = ProvingKey::build(OrchardCircuitVersion::PostNu6_3)
        .expect("current circuit supports proving");
    assert!(pk.prepare_proving());
    let vk = pk.verifying_key();
    for actions in [1, 2] {
        let fixture = payment_fixture(actions);
        let proofs = (0..count)
            .map(|index| {
                let proof = fixture
                    .bundle()
                    .authorization()
                    .create_proof(
                        &pk,
                        fixture.instances(),
                        proof_rng(CORPUS_DOMAIN, actions, 0, index as u64),
                    )
                    .expect("native corpus proof must succeed");
                proof
                    .verify(&vk, fixture.instances())
                    .expect("native corpus proof must verify");
                proof.as_ref().to_vec()
            })
            .collect();
        let corpus = VerifierCorpus {
            version: CORPUS_VERSION,
            actions,
            proofs,
        };
        let output = std::fs::File::create_new(directory.join(format!("verifier-{actions}.json")))
            .expect("create new verifier corpus");
        serde_json::to_writer(output, &corpus).expect("write verifier corpus");
    }
}

fn proof_rng(domain: u64, actions: usize, sequence: u64, index: u64) -> StdRng {
    let mut seed = <StdRng as SeedableRng>::Seed::default();
    for (chunk, component) in
        seed.chunks_exact_mut(SEED_COMPONENT_BYTES)
            .zip([domain, actions as u64, sequence, index])
    {
        chunk.copy_from_slice(&component.to_le_bytes());
    }
    StdRng::from_seed(seed)
}

fn median(values: &[u64]) -> f64 {
    let mut values = values.to_vec();
    values.sort_unstable();
    let middle = values.len() / 2;
    (values[middle] as f64 + values[(values.len() - 1) / 2] as f64) / 2.0
}

fn stable(values: &[u64]) -> bool {
    if values.len() < 2 * WARMUP_WINDOW {
        return false;
    }
    let recent = &values[values.len() - 2 * WARMUP_WINDOW..];
    let earlier = median(&recent[..WARMUP_WINDOW]);
    let later = median(&recent[WARMUP_WINDOW..]);
    (later / earlier - 1.0).abs() <= STABILITY_TOLERANCE
}

fn main() {
    let args: Vec<_> = std::env::args().skip(1).collect();
    if args
        .first()
        .is_some_and(|arg| arg == "--generate-verifier-fixtures")
    {
        assert_eq!(args.len(), GENERATE_ARGUMENTS);
        initialize_workers(requested_workers(&args[3]), false);
        generate_corpus(Path::new(&args[1]), args[2].parse().expect("corpus size"));
        return;
    }
    let mode = args
        .first()
        .expect("private worker requires prover or verifier mode");
    assert!(mode == "prover" || mode == "verifier");
    let verifier = mode == "verifier";
    assert_eq!(args.len(), LEG_ARGUMENTS + usize::from(verifier));
    let actions: usize = args[1].parse().expect("Action count");
    let batch_size: usize = args[2].parse().expect("batch size");
    assert!(batch_size > 0 && (verifier || batch_size == 1));
    let samples: usize = args[3].parse().expect("sample count");
    let warmup_seconds: f64 = args[4].parse().expect("warmup seconds");
    let sequence: u64 = args[5].parse().expect("seed sequence");
    let requested = requested_workers(&args[6]);
    assert!(samples > 0 && warmup_seconds.is_finite() && warmup_seconds >= 0.0);

    let workers = initialize_workers(requested, verifier);
    let backend = if cfg!(feature = "backend-sensei") {
        "sensei"
    } else {
        "native"
    };
    let fixture = payment_fixture(actions);
    let version = OrchardCircuitVersion::PostNu6_3;
    let mut corpus_hash = None;
    let mut proofs = Vec::new();
    if verifier {
        let bytes = std::fs::read(&args[LEG_ARGUMENTS]).expect("read shared verifier corpus");
        corpus_hash = Some(
            blake2b_simd::Params::new()
                .hash_length(CORPUS_HASH_BYTES)
                .hash(&bytes)
                .to_hex()
                .to_string(),
        );
        let corpus: VerifierCorpus =
            serde_json::from_slice(&bytes).expect("decode verifier corpus");
        assert_eq!(corpus.version, CORPUS_VERSION);
        assert_eq!(corpus.actions, actions);
        assert!(corpus.proofs.len() >= samples.max(2 * WARMUP_WINDOW).max(batch_size));
        assert_eq!(
            corpus.proofs.iter().collect::<BTreeSet<_>>().len(),
            corpus.proofs.len()
        );
        proofs = corpus.proofs.into_iter().map(Proof::new).collect();
    }
    println!(
        "{}",
        json!({
            "type": "metadata", "protocol": PROTOCOL_VERSION, "backend": backend, "mode": mode,
            "portable": cfg!(feature = "portable"), "workers": workers,
            "actions": actions, "samples": samples, "sequence": sequence,
            "batch_size": batch_size,
            "warmup_seconds": warmup_seconds,
            "corpus_blake2b": corpus_hash, "corpus_proofs": proofs.len(),
        })
    );

    if verifier {
        let vk = VerifyingKey::build(version);
        // Native preparation can be a no-op without orbits; its usual path is
        // still warmed by the untimed preflight and measured warmup below.
        vk.prepare_batch_validation();
        for proof in &proofs {
            proof
                .verify(&vk, fixture.instances())
                .expect("corpus preflight must verify");
        }
        run_leg(samples, warmup_seconds, |domain, index| {
            // Paired legs visit the same corpus entries. Selection, loading,
            // key/instance construction, and preflight are outside the timer.
            let offset = sequence as usize % proofs.len();
            let first = (offset + index as usize % proofs.len()) % proofs.len();
            let mut rng = proof_rng(domain, actions, sequence, index);
            if batch_size > 1 {
                // Queue construction, proof/instance copies, adapter translation,
                // random batch weights, and final verification are all timed.
                let start = Instant::now();
                let mut batch = ProofBatch::new(black_box(&vk));
                for index in 0..batch_size {
                    batch.add_proof(
                        black_box(&proofs[(first + index) % proofs.len()]),
                        black_box(fixture.instances()).to_vec(),
                    );
                }
                let valid = batch.validate(&mut rng);
                let elapsed = start.elapsed();
                assert!(valid, "benchmark batch must verify");
                return u64::try_from(elapsed.as_nanos()).expect("duration fits in u64");
            }
            let proof = &proofs[first];
            let start = Instant::now();
            let result = black_box(proof).verify(black_box(&vk), black_box(fixture.instances()));
            let elapsed = start.elapsed();
            result.expect("benchmark verification must succeed");
            u64::try_from(elapsed.as_nanos()).expect("duration fits in u64")
        });
        return;
    }

    let pk = ProvingKey::build(version).expect("current circuit supports proving");
    assert!(pk.prepare_proving());
    run_leg(samples, warmup_seconds, |domain, index| {
        let rng = proof_rng(domain, actions, sequence, index);
        // Bundle/witness generation, public instances, and RNG setup are all
        // outside this boundary. Sensei's adapter and request translation are in it.
        let start = Instant::now();
        let result = fixture.bundle().authorization().create_proof(
            black_box(&pk),
            black_box(fixture.instances()),
            rng,
        );
        let elapsed = start.elapsed();
        let proof = result.expect("benchmark proof must succeed");
        drop(black_box(proof));
        u64::try_from(elapsed.as_nanos()).expect("duration fits in u64")
    });
}

fn run_leg(samples: usize, warmup_seconds: f64, mut measure: impl FnMut(u64, u64) -> u64) {
    let mut warmup = Vec::new();
    let mut elapsed_seconds = 0.0;
    loop {
        let ns = measure(WARMUP_DOMAIN, warmup.len() as u64);
        warmup.push(ns);
        elapsed_seconds += std::time::Duration::from_nanos(ns).as_secs_f64();
        if warmup.len() >= 2 * WARMUP_WINDOW
            && elapsed_seconds >= warmup_seconds
            && (stable(&warmup) || elapsed_seconds >= MAX_WARMUP_SECONDS.max(warmup_seconds))
        {
            break;
        }
    }

    let mut measured = Vec::with_capacity(samples);
    for index in 0..samples {
        measured.push(measure(SAMPLE_DOMAIN, index as u64));
    }
    // JSON output follows the entire leg, outside all measurement boundaries.
    println!(
        "{}",
        json!({"type": "warmup", "ns": warmup, "stable": stable(&warmup)})
    );
    for (index, ns) in measured.iter().enumerate() {
        println!("{}", json!({"type": "sample", "index": index, "ns": ns}));
    }
    println!("{}", json!({"type": "complete", "samples": samples}));
}
