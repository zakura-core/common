//! Lower a group of gate constraints sharing one factor to a single weighted
//! product.
//!
//! Constraints `c_i = A · B_i` (or `B_i · A`) under one selector enter the
//! fused fold as `Σ_i P[slot_i] · c_i = A · Σ_i P[slot_i] · B_i`: the `B_i`
//! accumulate as unreduced limb products under their absolute slot weights,
//! one Montgomery reduction finishes the sum, and the fold pays one product
//! `A · sum` as a single limb product. A group of `n` constraints therefore
//! costs `n` limb products, one reduction, one full product and one limb
//! product instead of `n` full products and `n` limb products. The slots need
//! not be consecutive: the weights are absolute.
//!
//! The macro proves the structure from the shared source recipes at expansion
//! (one fixed root factor; every body a product with the same operand, all on
//! the left or all on the right) and emits straight-line arithmetic for the
//! shared factor and the other operands. A group without this shape is a
//! compile error.

use proc_macro2::{Span, TokenStream};
use quote::{format_ident, quote};
use sensei_shared::{
    expressions::{Expression, PROGRAM_COUNT},
    programs::expression_programs,
};
use syn::{
    Error, LitInt, Result, Token, bracketed,
    parse::{Parse, ParseStream},
    punctuated::Punctuated,
};

use crate::emit::{Emitter, shared_selector_bodies};

/// The macro's input: a bracketed list of program indices.
pub(crate) struct ProgramIndices(pub(crate) Vec<usize>);

impl Parse for ProgramIndices {
    fn parse(input: ParseStream) -> Result<Self> {
        let content;
        bracketed!(content in input);
        let literals: Punctuated<LitInt, Token![,]> =
            content.parse_terminated(LitInt::parse, Token![,])?;
        literals
            .iter()
            .map(LitInt::base10_parse)
            .collect::<Result<Vec<usize>>>()
            .map(Self)
    }
}

pub(crate) fn evaluate(programs: ProgramIndices) -> Result<TokenStream> {
    let programs = programs.0;
    if programs.len() < 2 {
        return Err(Error::new(
            Span::call_site(),
            "a factor group has at least two constraints",
        ));
    }
    if programs.windows(2).any(|pair| pair[0] >= pair[1]) {
        return Err(Error::new(
            Span::call_site(),
            "factor group programs must be strictly ascending",
        ));
    }
    if programs.iter().any(|&program| program >= PROGRAM_COUNT) {
        return Err(Error::new(
            Span::call_site(),
            "factor group program exceeds the program count",
        ));
    }
    let trees = expression_programs();
    let selected: Vec<&Expression> = programs.iter().map(|&program| &trees[program]).collect();
    emit_kernel(&programs, &selected)
}

/// The shared factor and the per-constraint other operands, borrowed.
#[derive(Debug)]
pub(crate) struct FactorGroup<'a> {
    pub(crate) factor: &'a Expression,
    pub(crate) others: Vec<&'a Expression>,
}

/// Recognizes `trees` as products sharing one operand — all on the left or
/// all on the right — under one selector.
pub(crate) fn recognize<'a>(trees: &[&'a Expression]) -> Result<FactorGroup<'a>> {
    let error = |message: &str| Error::new(Span::call_site(), message);
    let bodies = shared_selector_bodies(trees)?;
    let mut pairs = Vec::with_capacity(bodies.len());
    for body in bodies {
        let Expression::Product(left, right) = body else {
            return Err(error("a factor-group body is a product"));
        };
        pairs.push((left.as_ref(), right.as_ref()));
    }
    let (first_left, first_right) = pairs[0];
    if pairs.iter().all(|(left, _)| *left == first_left) {
        Ok(FactorGroup {
            factor: first_left,
            others: pairs.iter().map(|(_, right)| *right).collect(),
        })
    } else if pairs.iter().all(|(_, right)| *right == first_right) {
        Ok(FactorGroup {
            factor: first_right,
            others: pairs.iter().map(|(left, _)| *left).collect(),
        })
    } else {
        Err(error(
            "factor-group bodies must share one operand, all on the left or all on the right",
        ))
    }
}

fn emit_kernel(programs: &[usize], trees: &[&Expression]) -> Result<TokenStream> {
    let group = recognize(trees)?;
    let mut emitter = Emitter::default();
    let factor = emitter.value(group.factor)?;
    let others = group
        .others
        .iter()
        .map(|other| emitter.value(other))
        .collect::<Result<Vec<_>>>()?;
    let statements = emitter.statements;
    let first = programs[0];
    let name = format_ident!("weighted_factor_kernel_{first}");
    let list = programs
        .iter()
        .map(|program| program.to_string())
        .collect::<Vec<_>>()
        .join(", ");
    let doc = format!(
        "Generated by `weighted_factor_kernel!([{list}])`: the shared factor and the \
         reduced weighted sum of the other operands, whose product is \
         `Σ body[i] · powers[i]` over gate constraints {list}."
    );
    Ok(quote! {
        #[doc = #doc]
        #[inline(always)]
        fn #name(
            q: &[Fp; GATE_QUERY_COUNT],
            powers: &[Fp; GATE_CONSTRAINT_COUNT],
        ) -> (Fp, Fp) {
            #(#statements)*
            let weighted = Fp::sum_of_products(
                &[#(powers[#programs]),*],
                &[#(#others),*],
            );
            (#factor, weighted)
        }
    })
}

/// Every maximal group of at least `min_size` constraints of one gate whose
/// bodies share a factor: `(first program, all programs)`, in program order.
/// Gates are maximal runs of consecutive programs under one fixed root
/// factor. Used by the census test.
#[cfg(test)]
pub(crate) fn factor_groups(
    trees: &[Expression],
    gates: usize,
    min_size: usize,
) -> Vec<(usize, Vec<usize>)> {
    let mut groups = Vec::new();
    let mut start = 0;
    while start < gates {
        let selector = trees[start].fixed_root_split().map(|(factor, _)| factor);
        let mut end = start + 1;
        while end < gates && trees[end].fixed_root_split().map(|(factor, _)| factor) == selector {
            end += 1;
        }
        if selector.is_some() {
            let members: Vec<(usize, &Expression, &Expression)> = (start..end)
                .filter_map(|program| {
                    let (_, body) = trees[program].fixed_root_split()?;
                    match body {
                        Expression::Product(left, right) => {
                            Some((program, left.as_ref(), right.as_ref()))
                        }
                        _ => None,
                    }
                })
                .collect();
            for side in 0..2 {
                let mut seen: Vec<&Expression> = Vec::new();
                for &(program, left, right) in &members {
                    let operand = if side == 0 { left } else { right };
                    if seen.contains(&operand) {
                        continue;
                    }
                    seen.push(operand);
                    let group: Vec<usize> = members
                        .iter()
                        .filter(|(_, l, r)| (if side == 0 { *l } else { *r }) == operand)
                        .map(|(p, _, _)| *p)
                        .collect();
                    if group.len() >= min_size && group[0] == program {
                        groups.push((program, group));
                    }
                }
            }
        }
        start = end;
    }
    groups.sort();
    groups
}

#[cfg(test)]
mod tests {
    use super::*;

    fn compact(tokens: TokenStream) -> String {
        tokens
            .to_string()
            .chars()
            .filter(|c| !c.is_whitespace())
            .collect()
    }

    /// The census: every shared-factor group of at least three constraints in
    /// the 193 gate programs, with the product-equivalents each lowering
    /// removes per row per Action (`n − 1` full products less one reduction
    /// and one limb product, about `n − 1.9`).
    #[test]
    fn census_of_shared_factor_groups() {
        let trees = expression_programs();
        let groups = factor_groups(&trees, 193, 3);
        let expected: Vec<(usize, Vec<usize>)> = vec![
            (67, vec![67, 68, 69, 70, 72]),
            (105, vec![105, 111, 112, 114]),
            (106, vec![106, 115, 116, 118]),
            (132, vec![132, 133, 134]),
            (146, vec![146, 147, 148]),
            (149, vec![149, 153, 154, 155]),
            (169, vec![169, 170, 171]),
            (183, vec![183, 184, 185]),
            (186, vec![186, 190, 191, 192]),
        ];
        assert_eq!(
            groups, expected,
            "shared-factor census changed; update the fused fold's consumers"
        );
        // Source-level total: the sum over groups of (n − 1.9), about 15.9.
        // The fused fold realizes the gate-20, gate-32 and gate-43/54 groups
        // (9.4): the range banks fold in pairs at the second bank's slots, and
        // their three-member groups contain two products the fold already
        // computes once for several gates, so lowering them saves nothing.
        let total: f64 = groups.iter().map(|(_, g)| g.len() as f64 - 1.9).sum();
        assert!((15.0..17.0).contains(&total), "census total {total}");
    }

    #[test]
    fn recognizes_left_and_right_shared_factors() {
        let trees = expression_programs();
        let group = |programs: &[usize]| -> Vec<&Expression> {
            programs.iter().map(|&p| &trees[p]).collect()
        };
        let gate_20 = recognize(&group(&[67, 68, 69, 70, 72])).unwrap();
        assert_eq!(gate_20.factor, &sensei_shared::expressions::advice(8));
        assert_eq!(gate_20.others.len(), 5);
        // Gate 3's two bodies share the curve relation on the right.
        let gate_3 = recognize(&group(&[6, 7])).unwrap();
        assert_eq!(
            gate_3.others,
            vec![
                &sensei_shared::expressions::advice(0),
                &sensei_shared::expressions::advice(1)
            ]
        );
    }

    #[test]
    fn rejects_groups_without_a_shared_factor() {
        let trees = expression_programs();
        let group = |programs: &[usize]| -> Vec<&Expression> {
            programs.iter().map(|&p| &trees[p]).collect()
        };
        // Program 71's vanishing chain shares neither operand with gate 20's
        // `adv8` products.
        assert!(
            recognize(&group(&[67, 68, 71]))
                .unwrap_err()
                .to_string()
                .contains("share one operand")
        );
        assert!(
            recognize(&group(&[0, 1]))
                .unwrap_err()
                .to_string()
                .contains("product")
        );
        assert!(
            recognize(&group(&[10, 11]))
                .unwrap_err()
                .to_string()
                .contains("one selector")
        );
        assert!(
            recognize(&group(&[1, 3]))
                .unwrap_err()
                .to_string()
                .contains("share one operand")
        );
    }

    #[test]
    fn emits_the_gate_20_kernel() {
        let trees = expression_programs();
        let group = |programs: &[usize]| -> Vec<&Expression> {
            programs.iter().map(|&p| &trees[p]).collect()
        };
        let kernel =
            compact(emit_kernel(&[67, 68, 69, 70, 72], &group(&[67, 68, 69, 70, 72])).unwrap());
        assert!(kernel.contains("fnweighted_factor_kernel_67"));
        assert!(kernel.contains(
            "Fp::sum_of_products(&[powers[67usize],powers[68usize],powers[69usize],powers[70usize],powers[72usize]]"
        ));
        assert!(kernel.contains("(q[8usize],weighted)"));
    }

    #[test]
    fn evaluates_shared_factor_groups() {
        assert!(evaluate(ProgramIndices(vec![186, 190, 191, 192])).is_ok());
    }

    #[test]
    fn rejects_invalid_program_indices() {
        assert!(evaluate(ProgramIndices(vec![67])).is_err());
        assert!(evaluate(ProgramIndices(vec![68, 67])).is_err());
        assert!(evaluate(ProgramIndices(vec![67, 300])).is_err());
    }
}
