//! Recognize four consecutive gate constraints forming a rank-one bilinear
//! block and lower their challenge-weighted sum to a factored kernel.
//!
//! The fused gate fold owes constraint slot `i` the absolute power `P[i]`,
//! with `P[i] = y · P[i + 1]` for consecutive slots. Four consecutive
//! constraints at `s..s + 4` whose dynamic bodies are `(C · L_a) · R_b` for
//! `(a, b)` in `(0,0), (0,1), (1,0), (1,1)` therefore sum to
//!
//! ```text
//! Σ P[s + 2a + b] · C · L_a · R_b
//!   = C · (P[s + 1] · L_0 + P[s + 3] · L_1) · (y · R_0 + R_1).
//! ```
//!
//! The identity is polynomial in `y` (no division), so it holds for `y = 0`.
//! The macro proves the structure from the shared source recipes at
//! expansion — the four fixed root factors must be one selector and the
//! bodies must share their operands structurally — and emits straight-line
//! field arithmetic for the five operands followed by the factored form. A
//! slice whose recipes lack this shape is a compile error, not a silent
//! fallback.

use proc_macro2::{Span, TokenStream};
use quote::{format_ident, quote};
use sensei_shared::{
    expressions::{Expression, PROGRAM_COUNT},
    programs::expression_programs,
};
use syn::{Error, LitInt, Result};

use crate::emit::{Emitter, shared_selector_bodies};

/// Number of constraints one bilinear block covers.
pub(crate) const BLOCK_LEN: usize = 4;

pub(crate) fn evaluate(first: LitInt) -> Result<TokenStream> {
    let first: usize = first.base10_parse()?;
    if first + BLOCK_LEN > PROGRAM_COUNT {
        return Err(Error::new(
            Span::call_site(),
            format!(
                "bilinear block {first}..{} exceeds the program count",
                first + BLOCK_LEN
            ),
        ));
    }
    let trees = expression_programs();
    let selected: Vec<&Expression> = trees[first..first + BLOCK_LEN].iter().collect();
    emit_kernel(first, &selected)
}

/// The recognized operands of one bilinear block, borrowed from its trees.
#[derive(Debug)]
struct Bilinear<'a> {
    common: &'a Expression,
    left: [&'a Expression; 2],
    right: [&'a Expression; 2],
}

/// Splits one body `(C · L) · R` into its three operands.
fn split(body: &Expression) -> Result<(&Expression, &Expression, &Expression)> {
    let error = |message: &str| Error::new(Span::call_site(), message);
    let Expression::Product(inner, right) = body else {
        return Err(error("a bilinear body is a product"));
    };
    let Expression::Product(common, left) = inner.as_ref() else {
        return Err(error("a bilinear body's left operand is a product"));
    };
    Ok((common, left, right))
}

/// Checks that `trees` are one gate's `(C · L_a) · R_b` block, in the slot
/// order `(0,0), (0,1), (1,0), (1,1)`, under one shared fixed root factor.
fn recognize<'a>(trees: &[&'a Expression]) -> Result<Bilinear<'a>> {
    let error = |message: &str| Error::new(Span::call_site(), message);
    if trees.len() != BLOCK_LEN {
        return Err(error("a bilinear block has exactly four constraints"));
    }
    let bodies = shared_selector_bodies(trees)?;
    let (common, left_0, right_0) = split(bodies[0])?;
    let (_, _, right_1) = split(bodies[1])?;
    let (_, left_1, _) = split(bodies[2])?;
    let recognized = Bilinear {
        common,
        left: [left_0, left_1],
        right: [right_0, right_1],
    };
    for (index, body) in bodies.iter().enumerate() {
        let (body_common, body_left, body_right) = split(body)?;
        if body_common != recognized.common
            || body_left != recognized.left[index >> 1]
            || body_right != recognized.right[index & 1]
        {
            return Err(error(
                "bilinear bodies must be the shared operands in (0,0), (0,1), (1,0), (1,1) order",
            ));
        }
    }
    Ok(recognized)
}

fn emit_kernel(first: usize, trees: &[&Expression]) -> Result<TokenStream> {
    let bilinear = recognize(trees)?;
    let mut emitter = Emitter::default();
    let common = emitter.value(bilinear.common)?;
    let left_0 = emitter.value(bilinear.left[0])?;
    let left_1 = emitter.value(bilinear.left[1])?;
    let right_0 = emitter.value(bilinear.right[0])?;
    let right_1 = emitter.value(bilinear.right[1])?;
    let statements = emitter.statements;
    let name = format_ident!("weighted_bilinear_kernel_{first}");
    let [slot_0, slot_1, slot_2, slot_3] = [first, first + 1, first + 2, first + 3];
    let last = first + BLOCK_LEN;
    let doc = format!(
        "Generated by `weighted_bilinear_kernel!({first})`: the two factors whose \
         product is `Σ body[i] · powers[i]` over gate constraints `{first}..{last}`, \
         with `powers[{slot_0}] = y · powers[{slot_1}]` and \
         `powers[{slot_2}] = y · powers[{slot_3}]` (checked in debug builds)."
    );
    Ok(quote! {
        #[doc = #doc]
        #[inline(always)]
        fn #name(
            q: &[Fp; GATE_QUERY_COUNT],
            y: &Fp,
            powers: &[Fp; GATE_CONSTRAINT_COUNT],
        ) -> (Fp, Fp) {
            debug_assert_eq!(powers[#slot_0].reduce(), y.mul(&powers[#slot_1]).reduce());
            debug_assert_eq!(powers[#slot_2].reduce(), y.mul(&powers[#slot_3]).reduce());
            #(#statements)*
            let mut weighted_left = RowSum::new();
            weighted_left.add_product(&powers[#slot_1], &#left_0);
            weighted_left.add_product(&powers[#slot_3], &#left_1);
            let left = #common.mul(&weighted_left.finish());
            let right = y.mul(&#right_0).add(&#right_1);
            (left, right)
        }
    })
}

#[cfg(test)]
mod tests {
    use sensei_shared::expressions::{advice, constant, fixed, instance};
    use sensei_shared::programs::Value;

    use super::*;

    fn block(selector: Expression, operands: [Expression; 5]) -> Vec<Expression> {
        let [common, left_0, left_1, right_0, right_1] = operands;
        let body = |left: &Expression, right: &Expression| {
            common.clone().mul(left.clone()).mul(right.clone())
        };
        [
            body(&left_0, &right_0),
            body(&left_0, &right_1),
            body(&left_1, &right_0),
            body(&left_1, &right_1),
        ]
        .map(|body| selector.clone().mul(body))
        .into()
    }

    fn refs(trees: &[Expression]) -> Vec<&Expression> {
        trees.iter().collect()
    }

    fn operands() -> [Expression; 5] {
        [
            advice(0).mul(advice(2)),
            advice(2).sub(advice(0)),
            advice(3).add(advice(1)),
            advice(4).square().sub(advice(12)),
            advice(4).mul(advice(0)).sub(advice(13)),
        ]
    }

    /// The emitted tokens without whitespace, for layout-independent checks.
    fn compact(tokens: TokenStream) -> String {
        tokens
            .to_string()
            .chars()
            .filter(|c| !c.is_whitespace())
            .collect()
    }

    #[test]
    fn recognizes_the_gate_6_block() {
        let trees = expression_programs();
        let recognized = recognize(&refs(&trees[13..17])).unwrap();
        assert_eq!(recognized.common, &advice(0).mul(advice(2)));
        assert_eq!(recognized.left[0], &advice(2).sub(advice(0)));
        assert_eq!(recognized.left[1], &advice(3).add(advice(1)));
        assert_eq!(recognized.right[0].degree(), 2);
        assert_eq!(recognized.right[1].degree(), 2);
    }

    #[test]
    fn emits_the_gate_6_kernel() {
        let trees = expression_programs();
        let kernel = compact(emit_kernel(13, &refs(&trees[13..17])).unwrap());
        assert!(kernel.contains("fnweighted_bilinear_kernel_13"));
        assert!(kernel.contains("add_product(&powers[14usize],"));
        assert!(kernel.contains("add_product(&powers[16usize],"));
        assert!(kernel.contains(".square()"));
        assert!(!kernel.contains("negate"));
        assert!(!kernel.contains("scale"));
    }

    #[test]
    fn rejects_blocks_without_the_bilinear_shape() {
        let trees = expression_programs();
        let messages = |range: std::ops::Range<usize>| {
            emit_kernel(range.start, &refs(&trees[range]))
                .unwrap_err()
                .to_string()
        };
        // Gate 0's constraints share a selector but are not `(C · L) · R`.
        assert!(messages(0..4).contains("product"));
        // Straddling gates 5 and 6 mixes selectors.
        assert!(messages(9..13).contains("one selector"));
        // Shifting the block by one breaks the (0,0), (0,1), (1,0), (1,1) order.
        assert!(messages(14..18).contains("order"));

        let mut swapped = block(fixed(0), operands());
        swapped.swap(1, 2);
        assert!(
            recognize(&refs(&swapped))
                .unwrap_err()
                .to_string()
                .contains("order")
        );
        let mut ungated = block(fixed(0), operands());
        ungated[3] = advice(0).mul(advice(1));
        assert!(
            recognize(&refs(&ungated))
                .unwrap_err()
                .to_string()
                .contains("fixed root")
        );
        assert!(
            recognize(&refs(&swapped[..3]))
                .unwrap_err()
                .to_string()
                .contains("four")
        );
    }

    #[test]
    fn recognizes_constructed_bilinear_blocks() {
        assert!(recognize(&refs(&block(fixed(0), operands()))).is_ok());
    }

    #[test]
    fn evaluates_the_gate_6_block() {
        assert!(evaluate(LitInt::new("13", Span::call_site())).is_ok());
    }

    #[test]
    fn rejects_blocks_past_the_program_count() {
        assert!(evaluate(LitInt::new("204", Span::call_site())).is_err());
    }

    #[test]
    fn emitted_operands_share_repeated_subtrees_and_map_frame_slots() {
        let repeated = advice(5).add(constant(3));
        let trees = block(
            fixed(1),
            [
                repeated.clone().mul(repeated.clone()),
                repeated.clone().neg(),
                repeated.multiply_constant(7),
                fixed(2).sub(advice(1)),
                advice(1),
            ],
        );
        let kernel = compact(emit_kernel(0, &refs(&trees)).unwrap());
        // `advice(5) + constant(3)` is bound once and squared once.
        assert_eq!(
            kernel.matches("q[5usize].add(&constant(3usize))").count(),
            1
        );
        assert!(kernel.contains(".square()"));
        assert!(kernel.contains(".neg()"));
        assert!(kernel.contains("scale(&v"));
        // Fixed query 2 is frame slot 26: after the 25 advice slots and fixed
        // query 0.
        assert!(kernel.contains("q[26usize].sub(&q[1usize])"));
        assert!(kernel.contains("powers[1usize]"));
        assert!(kernel.contains("powers[3usize]"));
    }

    #[test]
    fn rejects_instance_operands() {
        let instance_block = block(
            fixed(0),
            [instance(0), advice(0), advice(1), advice(2), advice(3)],
        );
        assert!(
            emit_kernel(0, &refs(&instance_block))
                .unwrap_err()
                .to_string()
                .contains("instance")
        );
    }
}
