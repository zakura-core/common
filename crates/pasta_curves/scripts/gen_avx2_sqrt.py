#!/usr/bin/env python3
"""Generates the straight-line AVX2 Montgomery `mul` and `sqr` in
`src/arithmetic/avx2_sqrt.rs` (between the GENERATED markers).

Usage: python3 scripts/gen_avx2_sqrt.py [--check]

The loops are unrolled here rather than in Rust because LLVM kept the
variable-length inner loops and spilled an 18-column array; the unrolled
product-scanning form runs about twice as fast on Zen 4.

Product scanning: column k sums every a_i * b_j with i + j = k plus every
q_i * p_j with i < min(k, 9) and j = k - i, then a carry. For k < 9 the
column fixes q_k = -col mod 2^29 (p = 1 mod 2^29); for k >= 9 it emits an
output limb. Both Pasta moduli have radix-2^29 limbs 1..4 nonzero, 5..7
zero, and limb 8 equal to 2^22, so q * p_8 is a shift.
"""
import pathlib
import sys

L = 9
BEGIN = "// BEGIN GENERATED by scripts/gen_avx2_sqrt.py; do not edit.\n"
END = "// END GENERATED\n"


def tree(terms):
    while len(terms) > 1:
        nxt = [f"_mm256_add_epi64({terms[i]}, {terms[i + 1]})" for i in range(0, len(terms) - 1, 2)]
        if len(terms) % 2:
            nxt.append(terms[-1])
        terms = nxt
    return terms[0]


def gen(name, square):
    out = []
    args = "a: &V" if square else "a: &V, b: &V"
    doc = "Lane-wise Montgomery square." if square else "Lane-wise Montgomery product."
    out.append(f"/// {doc}")
    out.append('#[target_feature(enable = "avx2")]')
    out.append("#[inline]")
    # `mul` is shared with the batched chord additions in `avx2_chord`.
    vis = "pub(super) " if name == "mul" else ""
    out.append(f"{vis}fn {name}<const P0: u64, const P1: u64, const P2: u64, const P3: u64>({args}) -> V {{")
    out.append("    let p = const { pasta_limbs29(&[P0, P1, P2, P3]) };")
    out.append("    {")
    out.append("        let mask = _mm256_set1_epi64x(MASK as i64);")
    out.append("        let zero = _mm256_setzero_si256();")
    for j in range(1, 5):
        out.append(f"        let p{j} = _mm256_set1_epi64x(p[{j}] as i64);")
    out.append("        let a = &a.0;")
    if square:
        out.append("        let d: [__m256i; L] = core::array::from_fn(|i| _mm256_add_epi64(a[i], a[i]));")
    else:
        out.append("        let b = &b.0;")
    out.append("        let mut q = [zero; L];")
    out.append("        let mut out = [zero; L];")
    out.append("        let mut carry = zero;")
    for k in range(2 * L - 1):
        terms = []
        for i in range(L):
            j = k - i
            if not 0 <= j < L:
                continue
            if square:
                if j < i:
                    continue
                terms.append(f"_mm256_mul_epu32(a[{i}], a[{i}])" if i == j else f"_mm256_mul_epu32(a[{i}], d[{j}])")
            else:
                terms.append(f"_mm256_mul_epu32(a[{i}], b[{j}])")
        for i in range(min(k, L)):
            j = k - i
            if 1 <= j <= 4:
                terms.append(f"_mm256_mul_epu32(q[{i}], p{j})")
            elif j == 8:
                terms.append(f"_mm256_slli_epi64::<22>(q[{i}])")
        terms.append("carry")
        out.append(f"        let col = {tree(terms)};")
        if k < L:
            out.append(f"        q[{k}] = _mm256_and_si256(_mm256_sub_epi64(zero, col), mask);")
            out.append(f"        carry = _mm256_srli_epi64::<BITS>(_mm256_add_epi64(col, q[{k}]));")
        else:
            out.append(f"        out[{k - L}] = _mm256_and_si256(col, mask);")
            out.append("        carry = _mm256_srli_epi64::<BITS>(col);")
    out.append(f"        out[{L - 1}] = carry;")
    out.append("        V(out)")
    out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    path = pathlib.Path(__file__).resolve().parent.parent / "src/arithmetic/avx2_sqrt.rs"
    src = path.read_text()
    head, rest = src.split(BEGIN)
    _, tail = rest.split(END)
    body = gen("mul", False) + "\n" + gen("sqr", True)
    new = head + BEGIN + body + END + tail
    if "--check" in sys.argv:
        import subprocess, tempfile

        with tempfile.TemporaryDirectory() as tmp:
            formatted = pathlib.Path(tmp) / "avx2_sqrt.rs"
            formatted.write_text(new)
            subprocess.run(["rustfmt", "--edition", "2024", str(formatted)], check=True)
            current = formatted.read_text() == src
        if not current:
            sys.exit("avx2_sqrt.rs is out of date; rerun scripts/gen_avx2_sqrt.py and cargo fmt")
        return
    path.write_text(new)


if __name__ == "__main__":
    main()
