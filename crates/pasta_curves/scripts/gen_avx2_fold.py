#!/usr/bin/env python3
"""Generates the straight-line AVX2 fold kernels in
`src/arithmetic/avx2_fold.rs` (between the GENERATED markers).

Usage: python3 scripts/gen_avx2_fold.py [--check]

As in `gen_avx2_sqrt.py`, the loops are unrolled here: written as Rust loops
over a 17-column array, LLVM kept the outer loop, indexed the columns in
memory and copied the array with `memcpy`, running at half the speed of the
unrolled form on Zen 4.

- `mac_init` / `mac_add` write or add the 17 product columns of a 9-limb by
  9-limb product (column k sums every a_i * b_j with i + j = k).
- `carry_cols` moves each column's bits above 29 into the next; the top column
  keeps its own.
- `reduce_cols` carries, runs nine Montgomery rounds (q_i = -c_i mod 2^29
  because p = 1 mod 2^29; p's radix-2^29 limbs 1..4 are nonzero, 5..7 zero,
  and limb 8 is 2^22, so q * p_8 is a shift) and splits the top column into
  result limbs 7 and 8.
"""
import pathlib
import sys

L = 9
COLS = 2 * L - 1
BEGIN = "// BEGIN GENERATED by scripts/gen_avx2_fold.py; do not edit.\n"
END = "// END GENERATED\n"


def tree(terms):
    while len(terms) > 1:
        nxt = [f"_mm256_add_epi64({terms[i]}, {terms[i + 1]})" for i in range(0, len(terms) - 1, 2)]
        if len(terms) % 2:
            nxt.append(terms[-1])
        terms = nxt
    return terms[0]


def gen_mac(init):
    name = "mac_init" if init else "mac_add"
    doc = "Writes" if init else "Adds"
    out = [
        f"/// {doc} the product columns of `a b`.",
        '#[target_feature(enable = "avx2")]',
        "#[inline]",
        f"fn {name}(acc: &mut Cols, a: &V, b: &V) {{",
        "    let a = &a.0;",
        "    let b = &b.0;",
    ]
    for k in range(COLS):
        terms = [f"_mm256_mul_epu32(a[{i}], b[{k - i}])" for i in range(L) if 0 <= k - i < L]
        if not init:
            terms.append(f"load_col(&acc.0[{k}])")
        out.append(f"    let c{k} = {tree(terms)};")
        out.append(f"    store_col(&mut acc.0[{k}], c{k});")
    out.append("}")
    return "\n".join(out) + "\n"


def gen_carry():
    out = [
        "/// Moves each column's bits above 29 into the next (the top keeps its own).",
        '#[target_feature(enable = "avx2")]',
        "#[inline]",
        "fn carry_cols(acc: &mut Cols) {",
        "    let mask = _mm256_set1_epi64x(MASK as i64);",
        "    let v = load_col(&acc.0[0]);",
        "    store_col(&mut acc.0[0], _mm256_and_si256(v, mask));",
        "    let mut carry = _mm256_srli_epi64::<BITS>(v);",
    ]
    for k in range(1, COLS - 1):
        out.append(f"    let v = _mm256_add_epi64(load_col(&acc.0[{k}]), carry);")
        out.append(f"    store_col(&mut acc.0[{k}], _mm256_and_si256(v, mask));")
        out.append("    carry = _mm256_srli_epi64::<BITS>(v);")
    out.append(f"    let top = _mm256_add_epi64(load_col(&acc.0[{COLS - 1}]), carry);")
    out.append(f"    store_col(&mut acc.0[{COLS - 1}], top);")
    out.append("}")
    return "\n".join(out) + "\n"


def gen_reduce():
    out = [
        "/// The Montgomery reduction of the columns, `X / 2^261 mod p`, lazily",
        "/// reduced (below `X / 2^261 + p`) and normalized.",
        '#[target_feature(enable = "avx2")]',
        "#[inline]",
        "fn reduce_cols<const P0: u64, const P1: u64, const P2: u64, const P3: u64>(acc: &Cols) -> V {",
        "    let p = const { pasta_limbs29(&[P0, P1, P2, P3]) };",
        "    let mask = _mm256_set1_epi64x(MASK as i64);",
        "    let zero = _mm256_setzero_si256();",
    ]
    for j in range(1, 5):
        out.append(f"    let p{j} = _mm256_set1_epi64x(p[{j}] as i64);")
    # Carry columns 0..15; column 16 keeps the rest.
    out.append("    let v = load_col(&acc.0[0]);")
    out.append("    let c0 = _mm256_and_si256(v, mask);")
    out.append("    let mut k = _mm256_srli_epi64::<BITS>(v);")
    for c in range(1, COLS - 1):
        out.append(f"    let v = _mm256_add_epi64(load_col(&acc.0[{c}]), k);")
        mut = "mut " if c <= COLS - 1 else ""
        out.append(f"    let {mut}c{c} = _mm256_and_si256(v, mask);")
        out.append("    k = _mm256_srli_epi64::<BITS>(v);")
    out.append(f"    let mut c{COLS - 1} = _mm256_add_epi64(load_col(&acc.0[{COLS - 1}]), k);")
    # Montgomery rounds.
    for i in range(L):
        out.append(f"    let q = _mm256_and_si256(_mm256_sub_epi64(zero, c{i}), mask);")
        out.append(f"    let carry = _mm256_srli_epi64::<BITS>(_mm256_add_epi64(c{i}, q));")
        out.append(f"    c{i + 1} = _mm256_add_epi64(_mm256_add_epi64(c{i + 1}, carry), _mm256_mul_epu32(q, p1));")
        for j in range(2, 5):
            out.append(f"    c{i + j} = _mm256_add_epi64(c{i + j}, _mm256_mul_epu32(q, p{j}));")
        out.append(f"    c{i + 8} = _mm256_add_epi64(c{i + 8}, _mm256_slli_epi64::<22>(q));")
    # Result columns 9..16 into nine normalized limbs.
    out.append("    let _ = (c0, c1, c2, c3, c4, c5, c6, c7, c8);")
    out.append(f"    let r0 = _mm256_and_si256(c{L}, mask);")
    out.append(f"    let mut k = _mm256_srli_epi64::<BITS>(c{L});")
    for r in range(1, L - 2):
        out.append(f"    let v = _mm256_add_epi64(c{L + r}, k);")
        out.append(f"    let r{r} = _mm256_and_si256(v, mask);")
        out.append("    k = _mm256_srli_epi64::<BITS>(v);")
    out.append(f"    let top = _mm256_add_epi64(c{COLS - 1}, k);")
    out.append(f"    let r{L - 2} = _mm256_and_si256(top, mask);")
    out.append(f"    let r{L - 1} = _mm256_srli_epi64::<BITS>(top);")
    out.append("    V([" + ", ".join(f"r{r}" for r in range(L)) + "])")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    path = pathlib.Path(__file__).resolve().parent.parent / "src/arithmetic/avx2_fold.rs"
    src = path.read_text()
    head, rest = src.split(BEGIN)
    _, tail = rest.split(END)
    body = gen_mac(True) + "\n" + gen_mac(False) + "\n" + gen_carry() + "\n" + gen_reduce()
    new = head + BEGIN + body + END + tail
    if "--check" in sys.argv:
        import subprocess, tempfile

        with tempfile.TemporaryDirectory() as tmp:
            formatted = pathlib.Path(tmp) / "avx2_fold.rs"
            formatted.write_text(new)
            subprocess.run(["rustfmt", "--edition", "2024", str(formatted)], check=True)
            current = formatted.read_text() == src
        if not current:
            sys.exit("avx2_fold.rs is out of date; rerun scripts/gen_avx2_fold.py and cargo fmt")
        return
    path.write_text(new)


if __name__ == "__main__":
    main()
