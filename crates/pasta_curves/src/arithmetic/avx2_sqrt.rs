/// Packs four little-endian 256-bit integers (each below 2^261).
pub(crate) fn pack(x: &[[u64; 4]; 4]) -> V {
    // SAFETY: this module is only compiled with the `avx2` target feature.
    unsafe {
        let l = x.map(|x| to29(&x));
        V(core::array::from_fn(|i| {
            _mm256_set_epi64x(
                l[3][i] as i64,
                l[2][i] as i64,
                l[1][i] as i64,
                l[0][i] as i64,
            )
        }))
    }
}

/// Unpacks four integers; limbs 0..8 must be below 2^29 (as `mul` and `sqr` leave them).
pub(crate) fn unpack(v: &V) -> [[u64; 4]; 4] {
    // SAFETY: this module is only compiled with the `avx2` target feature, and
    // each store writes exactly the 32 bytes of one `[u64; 4]`.
    unsafe {
        let mut limbs = [[0u64; 4]; L];
        for (dst, src) in limbs.iter_mut().zip(&v.0) {
            // Stores 32 bytes into the 32-byte array `dst`.
            _mm256_storeu_si256(dst.as_mut_ptr() as *mut __m256i, *src);
        }
        core::array::from_fn(|lane| {
            let mut out = [0u64; 4];
            for (i, limb) in limbs.iter().enumerate() {
                let bit = i * BITS as usize;
                let (w, s) = (bit / 64, bit % 64);
                let x = limb[lane];
                out[w] |= x << s;
                if s + BITS as usize > 64 && w + 1 < 4 {
                    out[w + 1] |= x >> (64 - s);
                }
            }
            out
        })
    }
}

/// A field whose square-root chain can run in four-way AVX2 lanes.
pub(crate) trait Avx2Chain: SqrtTableHelpers {
    /// Montgomery limbs (`a * 2^256 mod p`), canonical.
    fn limbs(&self) -> [u64; 4];
    /// Builds an element from canonical Montgomery limbs.
    fn from_limbs(limbs: [u64; 4]) -> Self;
    /// Canonicalizes a value below `2p`.
    fn canonical_limbs(limbs: [u64; 4]) -> [u64; 4];
    /// `2^266 mod p` as an integer (enters the `R'` domain from Montgomery limbs).
    fn c_in() -> [u64; 4];
    /// `2^256 mod p` as an integer (leaves the `R'` domain to Montgomery limbs).
    fn c_out() -> [u64; 4];
    /// Lane-wise `x^((t-1)/2)` in the `R'` domain.
    fn pow_chain<const G: usize>(x: &[V; G]) -> [V; G];
    /// Lane-wise squaring in the `R'` domain.
    fn sqr_v(a: &V) -> V;
    /// Lane-wise product in the `R'` domain.
    fn mul_v(a: &V, b: &V) -> V;
}

/// Lane-wise `a^(2^n)` over `G` vectors.
#[inline(always)]
pub(crate) fn sqr_n<F: Avx2Chain, const G: usize>(a: &[V; G], n: u32) -> [V; G] {
    let mut t = *a;
    for _ in 0..n {
        for v in t.iter_mut() {
            *v = F::sqr_v(v);
        }
    }
    t
}

/// Lane-wise products over `G` vectors.
#[inline(always)]
pub(crate) fn mul_g<F: Avx2Chain, const G: usize>(a: &[V; G], b: &[V; G]) -> [V; G] {
    core::array::from_fn(|g| F::mul_v(&a[g], &b[g]))
}

/// Interprets an addition chain: `smalls` are `x^3, x^7, x^9, x^11, x^13`
/// selected by exponent; `steps` are `(squarings, exponent)` pairs.
#[inline(always)]
pub(crate) fn run_chain<F: Avx2Chain, const G: usize>(
    x: &[V; G],
    steps: &[(u32, u32)],
    final_squarings: u32,
) -> [V; G] {
    let x2 = sqr_n::<F, G>(x, 1);
    let x3 = mul_g::<F, G>(&x2, x);
    let x7 = mul_g::<F, G>(&sqr_n::<F, G>(&x3, 1), x);
    let x9 = mul_g::<F, G>(&x7, &x2);
    let x11 = mul_g::<F, G>(&x9, &x2);
    let x13 = mul_g::<F, G>(&x11, &x2);
    let pick = |e: u32| match e {
        1 => x,
        3 => &x3,
        7 => &x7,
        9 => &x9,
        11 => &x11,
        13 => &x13,
        _ => unreachable!(),
    };
    let mut acc = *x;
    for &(n, e) in steps {
        acc = mul_g::<F, G>(&sqr_n::<F, G>(&acc, n), pick(e));
    }
    sqr_n::<F, G>(&acc, final_squarings)
}

/// Converts `4G` scalar elements into the `R'` domain.
pub(crate) fn enter<F: Avx2Chain, const G: usize>(u: &[F], c_in: &V) -> [V; G] {
    core::array::from_fn(|g| {
        let v = pack(&core::array::from_fn(|k| u[4 * g + k].limbs()));
        F::mul_v(&v, c_in)
    })
}

/// Converts `R'`-domain vectors back to scalar elements.
pub(crate) fn leave<F: Avx2Chain, const G: usize>(v: &[V; G], c_out: &V, out: &mut [F]) {
    for g in 0..G {
        let w = unpack(&F::mul_v(&v[g], c_out));
        for k in 0..4 {
            out[4 * g + k] = F::from_limbs(F::canonical_limbs(w[k]));
        }
    }
}
