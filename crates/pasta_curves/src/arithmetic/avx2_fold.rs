//! Four-way AVX2 deferred multiply-accumulate for the Pasta fields.
//!
//! `halo2_proofs`' evaluator folds many weighted terms, `sum_k t_k s_k`, per
//! row. The scalar path accumulates unreduced 512-bit products and reduces
//! once per sum ([`crate::deferred`]). This module does the same four rows at
//! a time in the radix-2^29 arithmetic of [`super::avx2_sqrt`] (availability
//! and the AVX2 guarantee are documented there). Only AVX2 is used.
//!
//! # Accumulator
//!
//! Each lane holds the schoolbook product columns of a 9-limb by 9-limb
//! product: [`COLS`] 64-bit columns, column `c` weighing `2^(29 c)`. A term
//! adds at most nine partial products below `2^58` to a column, so columns
//! that start below `2^30` stay below `2^64` for seven terms; a carry pass
//! after every [`CARRY_EVERY`] terms moves each column's bits above 29 into
//! the next. The top column is never masked: it holds every bit from
//! `2^464` up, which stays far below `2^64` for the term counts allowed here.
//!
//! # Domain and bounds
//!
//! Terms are canonical Montgomery values `t 2^256`. The other factor (a
//! broadcast power or a per-row factor) is scaled by 32 to `s 2^261`, so a
//! sum of `T` products is `X = sum t s 2^517 < 32 T p^2`. Nine Montgomery
//! rounds (`p = 1 mod 2^29`, so each round's factor is a negation) give
//! `(X + Q p) / 2^261 < 32 T p^2 / 2^261 + p < (T / 4 + 1) p`, the scalar
//! Montgomery form `sum t s 2^256` lazily reduced. [`reduce`] accepts sums of
//! at most [`MAX_TERMS`] terms, so the value stays below `64 p`, which
//! `reduce64` brings to canonical form; longer sums are reduced in parts by
//! the caller.
#![allow(unsafe_code)]

use core::arch::x86_64::*;

use alloc::vec::Vec;

use super::avx2_fft::{from_words, normalize, reduce64, to_words};
use super::avx2_sqrt::{BITS, L, MASK, V, pasta_limbs29};

/// Product columns per lane.
const COLS: usize = 2 * L - 1;
/// Terms between carry passes.
const CARRY_EVERY: u32 = 6;
/// The most terms one [`reduce`] accepts (`(T / 4 + 1) p < 64 p`).
pub(crate) const MAX_TERMS: u32 = 248;

/// The product columns of four rows, lane-major per column.
#[derive(Clone, Copy, Default)]
#[repr(C, align(32))]
pub(crate) struct Cols([[u64; 4]; COLS]);

/// Accumulators for a run of rows (four per [`Cols`]).
#[derive(Clone, Default)]
pub(crate) struct Lanes {
    cols: Vec<Cols>,
    len: usize,
    /// Terms since the last carry pass.
    pending: u32,
    /// Terms since the last (re)initialization.
    terms: u32,
}

impl Lanes {
    pub(crate) fn resize(&mut self, len: usize) {
        self.cols.resize(len.div_ceil(4), Cols::default());
        self.len = len;
    }

    pub(crate) fn len(&self) -> usize {
        self.len
    }

    /// Terms accumulated since initialization.
    pub(crate) fn terms(&self) -> u32 {
        self.terms
    }
}

#[target_feature(enable = "avx2")]
#[inline]
fn load_col(c: &[u64; 4]) -> __m256i {
    // SAFETY: `Cols` is 32-byte aligned and each column is 32 bytes.
    unsafe { _mm256_load_si256(c.as_ptr() as *const __m256i) }
}

#[target_feature(enable = "avx2")]
#[inline]
fn store_col(c: &mut [u64; 4], v: __m256i) {
    // SAFETY: as for `load_col`.
    unsafe { _mm256_store_si256(c.as_mut_ptr() as *mut __m256i, v) }
}

