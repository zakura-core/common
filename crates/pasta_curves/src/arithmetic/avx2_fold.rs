/// `32 a`, normalized.
#[target_feature(enable = "avx2")]
#[inline]
fn shl5(a: &V) -> V {
    let mut v = a.0;
    for limb in v.iter_mut() {
        *limb = _mm256_slli_epi64::<5>(*limb);
    }
    normalize(v)
}

/// Loads up to four rows, zero-padding a short tail.
#[target_feature(enable = "avx2")]
#[inline]
fn load_rows(x: &[[u64; 4]]) -> V {
    if x.len() == 4 {
        from_words(x)
    } else {
        let mut padded = [[0u64; 4]; 4];
        padded[..x.len()].copy_from_slice(x);
        from_words(&padded)
    }
}

/// Accumulates `terms[i] * power32` into row `i`, where `power32` is the
/// canonical Montgomery form of 32 times the power. `init` starts a new sum.
#[target_feature(enable = "avx2")]
pub(crate) fn accumulate_power(
    lanes: &mut Lanes,
    terms: &[[u64; 4]],
    power32: [u64; 4],
    init: bool,
) {
    assert_eq!(terms.len(), lanes.len);
    let s = from_words(&[power32; 4]);
    let after_carry = begin_term(lanes, init);
    for (acc, t) in lanes.cols.iter_mut().zip(terms.chunks(4)) {
        let t = load_rows(t);
        if init {
            mac_init(acc, &t, &s);
        } else {
            mac_add(acc, &t, &s);
            if after_carry {
                carry_cols(acc);
            }
        }
    }
}

/// Accumulates `terms[i] * factors[i]` into row `i` (both canonical
/// Montgomery limbs). `init` starts a new sum.
#[target_feature(enable = "avx2")]
pub(crate) fn accumulate_products(
    lanes: &mut Lanes,
    terms: &[[u64; 4]],
    factors: &[[u64; 4]],
    init: bool,
) {
    assert_eq!(terms.len(), lanes.len);
    assert_eq!(factors.len(), lanes.len);
    let after_carry = begin_term(lanes, init);
    for ((acc, t), f) in lanes
        .cols
        .iter_mut()
        .zip(terms.chunks(4))
        .zip(factors.chunks(4))
    {
        let t = load_rows(t);
        let f = shl5(&load_rows(f));
        if init {
            mac_init(acc, &t, &f);
        } else {
            mac_add(acc, &t, &f);
            if after_carry {
                carry_cols(acc);
            }
        }
    }
}

/// Updates the term counters; returns whether this term ends a carry period.
fn begin_term(lanes: &mut Lanes, init: bool) -> bool {
    if init {
        lanes.terms = 1;
        lanes.pending = 1;
        return false;
    }
    assert!(
        lanes.terms < MAX_TERMS,
        "a deferred sum exceeded its term limit"
    );
    lanes.terms += 1;
    lanes.pending += 1;
    if lanes.pending == CARRY_EVERY {
        lanes.pending = 0;
        true
    } else {
        false
    }
}

/// Writes each row's sum, canonical, to `out`.
#[target_feature(enable = "avx2")]
pub(crate) fn reduce<const P0: u64, const P1: u64, const P2: u64, const P3: u64>(
    lanes: &Lanes,
    out: &mut [[u64; 4]],
) {
    let p = const { pasta_limbs29(&[P0, P1, P2, P3]) };
    assert_eq!(out.len(), lanes.len);
    for (acc, out) in lanes.cols.iter().zip(out.chunks_mut(4)) {
        let v = reduce64(&reduce_cols::<P0, P1, P2, P3>(acc), &p);
        if out.len() == 4 {
            to_words(&v, out);
        } else {
            let mut padded = [[0u64; 4]; 4];
            to_words(&v, &mut padded);
            let n = out.len();
            out.copy_from_slice(&padded[..n]);
        }
    }
}
