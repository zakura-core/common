//! Write artifacts and render their consumer paths.
//!
//! Encoders return bytes in Udon's fixed stored representation; this crate's
//! filesystem output is confined to this module. Sensei's build script writes
//! its complete-selector payload and build manifest separately.

use std::{fs, path::Path};

use crate::{ARTIFACTS, ArtifactId, Error, RawStore, context::Context, registry::ENCODERS};

/// File name of the generated path macro under `OUT_DIR`.
pub const ARTIFACT_PATHS_FILE: &str = "artifact-paths.rs";

/// Renders the `artifact_path!` macro Sensei includes at its crate root:
/// one arm per registered artifact (embedded or not, so a dial
/// change needs no consumer edit), mapping [`crate::Artifact::ident`] to
/// the exact output path under `out_dir` as a string literal. The registry is
/// the only place that spells stems, stored-form descriptors, and extensions;
/// the embedding declarations state only the record layout.
/// This covers registered artifacts; Sensei's separate complete-selector output
/// uses the direct consumer path described by [`ArtifactId::GateSelectors`].
pub fn render_artifact_paths(out_dir: &Path) -> String {
    let mut source = String::new();
    source.push_str(
        "// Generated by `sensei-artifacts` at build time: artifact identifiers to their\n",
    );
    source.push_str(
        "// exact output paths. Do not edit; the registry in `sensei-artifacts` is the source.\n",
    );
    source.push_str("macro_rules! artifact_path {\n");
    for artifact in ARTIFACTS {
        let path = out_dir.join(artifact.file_name());
        // `{:?}` on the path's string form yields a valid Rust string literal
        // (backslashes and quotes escaped), whatever the host's separators.
        source.push_str(&format!(
            "    ({}) => {{\n        {:?}\n    }};\n",
            artifact.ident(),
            path.to_string_lossy()
        ));
    }
    source.push_str("}\n");
    source
}

/// Generates enabled artifacts into `out_dir` using Udon's fixed stored form.
///
/// Uses [`sensei_shared::commitment_tables::DEFAULT`], so selecting
/// [`ArtifactId::CommitmentTables`] writes an empty file. Sensei's `build.rs`
/// uses [`emit_generated_with_commitment_tables`] for its source-selected policy.
///
/// Only entries in `enabled` are emitted. Returns the produced
/// file names in registry order. This entry point works both in build scripts
/// and in standalone callers, without consulting the target environment.
/// Encoders share lazily prepared points, tables, and polynomials within this
/// call; all preparation is released when the call returns.
///
/// The caller must create `out_dir`. Existing output files are overwritten;
/// emission stops at the first error and leaves earlier writes in place.
/// The path macro is written last and is not included in the returned names.
pub fn emit_generated(
    raw: &RawStore,
    out_dir: &Path,
    enabled: &[ArtifactId],
) -> Result<Vec<String>, Error> {
    emit_generated_with_commitment_tables(
        raw,
        out_dir,
        enabled,
        sensei_shared::commitment_tables::DEFAULT,
    )
}

/// Emits artifacts with an explicit commitment-table policy.
///
/// Sensei's `build.rs` passes `tuning::COMMITMENT_TABLES` here. The policy changes
/// the commitment-table payload without changing its name, and may produce an
/// empty payload when no entries are embedded. Reproducing the bytes requires
/// the same raw inputs, recipes, stored form, and policy. All other encoders and
/// output behavior, including preparation lifetimes, overwrites, and partial
/// writes on error, are identical to [`emit_generated`].
///
/// # Panics
///
/// Calls [`Config::validate`](sensei_shared::commitment_tables::Config::validate)
/// before any file is written, even when commitment tables are not in `enabled`.
/// Invalid widths or exceeded memory ceilings panic instead of returning an
/// [`Error`] or adjusting the policy.
pub fn emit_generated_with_commitment_tables(
    raw: &RawStore,
    out_dir: &Path,
    enabled: &[ArtifactId],
    config: sensei_shared::commitment_tables::Config,
) -> Result<Vec<String>, Error> {
    config.validate();
    let context = Context::with_commitment_tables(raw, config);
    let mut produced = Vec::new();
    for (artifact, encode) in ARTIFACTS.iter().zip(ENCODERS) {
        if !enabled.contains(&artifact.id) {
            continue;
        }
        let bytes = encode(&context)?;
        let name = artifact.file_name();
        let path = out_dir.join(&name);
        fs::write(&path, &bytes)
            .map_err(|error| Error::new(format!("writing {}: {error}", path.display())))?;
        produced.push(name);
    }
    // The consumer-side glue: every declaration reads its path from here.
    let paths = out_dir.join(ARTIFACT_PATHS_FILE);
    fs::write(&paths, render_artifact_paths(out_dir))
        .map_err(|error| Error::new(format!("writing {}: {error}", paths.display())))?;
    Ok(produced)
}
